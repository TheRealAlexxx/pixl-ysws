function glyph(ch: string): number[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "]!;
}

export function textWidth(text: string, scale: number, tracking = 1): number {
  if (!text.length) return 0;
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

export function drawText(
  canvas: Canvas,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: Rgb,
  tracking = 1,
): void {
  let cursor = x;
  for (const ch of text) {
    const rows = glyph(ch);
    for (let ry = 0; ry < GLYPH_H; ry++) {
      const bits = rows[ry]!;
      for (let rx = 0; rx < GLYPH_W; rx++) {
        if (bits & (1 << (GLYPH_W - 1 - rx))) {
          canvas.fill(cursor + rx * scale, y + ry * scale, scale, scale, color);
        }
      }
    }
    cursor += (GLYPH_W + tracking) * scale;
  }
}

export function wrap(text: string, scale: number, maxWidth: number, tracking = 1): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (line && textWidth(candidate, scale, tracking) > maxWidth) {
      lines.push(line);
      line = word;
    } else {
      line = candidate;
    }
  }
  if (line) lines.push(line);
  return lines;
}
